import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { SampleOutageGenerator, type ScenarioType } from '../src/generator/sampleOutageGenerator.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const scenarios: ScenarioType[] = [
  'rds_bottleneck',
  'container_crashloop',
  'security_group_drift',
  'api_5xx_timeouts',
  'finops_idle_waste',
];

const datasetsDir = path.resolve(__dirname, '../datasets');
if (!fs.existsSync(datasetsDir)) {
  fs.mkdirSync(datasetsDir, { recursive: true });
}

console.log('\n📦 Exporting Handoff 1 Datasets for Gargi...\n');

const manifest: Array<{
  scenario: string;
  filename: string;
  alarmsCount: number;
  logsCount: number;
  trailEventsCount: number;
  canvasNodesCount: number;
  description: string;
}> = [];

for (const sc of scenarios) {
  const payload = SampleOutageGenerator.generate(sc);
  const filename = `alertPayload-${sc}.json`;
  const filePath = path.join(datasetsDir, filename);

  fs.writeFileSync(filePath, JSON.stringify(payload, null, 2), 'utf8');
  console.log(`✅ Saved: datasets/${filename}`);

  manifest.push({
    scenario: sc,
    filename,
    alarmsCount: payload.activeAlarms.length,
    logsCount: payload.cloudWatchLogs30m.length,
    trailEventsCount: payload.cloudTrailEvents60m.length,
    canvasNodesCount: payload.canvasGraph.nodes.length,
    description: payload.activeAlarms[0]?.alarmName || sc,
  });
}

// Write README for Gargi in the datasets directory
const readmeContent = `# 📦 ArchViz Autonomous — Handoff 1 Test Datasets for Gargi

These datasets contain the exact **Handoff 1 JSON payloads** generated by Krish's AWS Telemetry Pipeline for the 5 target failure scenarios.

Use these files to build, train, and benchmark your **Diagnostic & RCA Engine** (\`runAutomatedRcaPipeline\`), Alert Deduplicator (\`buildDependencyGraph.ts\`), and RAG Vector Retriever (\`RagRetrieverNode.tsx\`).

---

## 📋 Dataset Files

${manifest
  .map(
    m => `### \`${m.filename}\` (${m.scenario})
- **Active Alarms:** ${m.alarmsCount}
- **Filtered CloudWatch Logs (30m):** ${m.logsCount} lines
- **CloudTrail Events (60m):** ${m.trailEventsCount} events
- **Canvas Nodes:** ${m.canvasNodesCount} nodes
- **Description:** ${m.description}
`
  )
  .join('\n')}

---

## 🔍 How to Use in Your Code

Each file strictly conforms to the \`AlertPayload\` interface in \`src/types/alertPayload.ts\`:

\`\`\`typescript
import type { AlertPayload } from 'archviz-autonomous';
import rdsDataset from './datasets/alertPayload-rds_bottleneck.json';

// Feed directly into your RCA function:
const result = await runAutomatedRcaPipeline(rdsDataset as AlertPayload);
\`\`\`
`;

fs.writeFileSync(path.join(datasetsDir, 'README.md'), readmeContent, 'utf8');
console.log('✅ Created: datasets/README.md');
console.log('\n🎉 All 5 datasets exported successfully!\n');
